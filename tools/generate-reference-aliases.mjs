#!/usr/bin/env node
import { mkdir, readFile, stat, writeFile } from 'node:fs/promises';
import { dirname, posix, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const RULES_SCHEMA = 'conscience64.reference-rules/v1';

function localPath(value, label) {
  if (typeof value !== 'string' || !value) throw new Error(`${label} must be a non-empty string`);
  if (value.startsWith('/') || value.includes('\\') || /^[a-z][a-z0-9+.-]*:/i.test(value)) throw new Error(`${label} outside repository: ${value}`);
  const parts = value.split('/');
  if (parts.some(part => !part || part === '.' || part === '..')) throw new Error(`${label} escapes repository: ${value}`);
  return value;
}

function escapeHtml(value) {
  return value.replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
}

export function renderAliasPage(alias, target) {
  const aliasPath = localPath(alias, 'alias');
  const targetPath = localPath(target, 'target');
  const relative = posix.relative(posix.dirname(aliasPath), targetPath) || posix.basename(targetPath);
  const href = escapeHtml(relative);
  const jsTarget = JSON.stringify(relative);
  return `<!doctype html>\n<html lang="en">\n<head>\n  <meta charset="utf-8">\n  <meta name="viewport" content="width=device-width,initial-scale=1">\n  <meta name="robots" content="noindex">\n  <meta http-equiv="refresh" content="0;url=${href}">\n  <link rel="canonical" href="${href}">\n  <title>Moved · Conscience64</title>\n</head>\n<body>\n  <main>\n    <h1>This reference moved</h1>\n    <p><a href="${href}">Continue to the canonical resource</a>.</p>\n  </main>\n  <script>\n    const target=${jsTarget};\n    location.replace(target + location.search + location.hash);\n  </script>\n</body>\n</html>\n`;
}

export async function generateDeclaredAliases({ root = process.cwd(), check = false } = {}) {
  const rulesPath = resolve(root, 'play/reference-rules.json');
  const rules = JSON.parse(await readFile(rulesPath, 'utf8'));
  if (rules.schema !== RULES_SCHEMA) throw new Error(`unexpected rules schema: ${rules.schema}`);

  const results = [];
  for (const [alias, declaration] of Object.entries(rules.aliases || {})) {
    const target = typeof declaration === 'string' ? declaration : declaration?.target ?? declaration?.resolved;
    const aliasPath = localPath(alias, 'alias');
    const targetPath = localPath(target, 'target');
    await stat(resolve(root, targetPath));
    const expected = renderAliasPage(aliasPath, targetPath);
    const outputPath = resolve(root, aliasPath);

    if (check) {
      const actual = await readFile(outputPath, 'utf8');
      if (actual !== expected) throw new Error(`generated alias drift: ${aliasPath}`);
    } else {
      await mkdir(dirname(outputPath), { recursive: true });
      await writeFile(outputPath, expected, 'utf8');
    }
    results.push({ alias: aliasPath, target: targetPath });
  }
  return results;
}

const invoked = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invoked) {
  try {
    const check = process.argv.includes('--check');
    const results = await generateDeclaredAliases({ check });
    console.log(`PASS reference aliases: ${results.length} declared alias${results.length === 1 ? '' : 'es'} ${check ? 'match generated bytes' : 'generated'}`);
  } catch (error) {
    console.error(`FAIL reference aliases: ${error.message}`);
    process.exitCode = 1;
  }
}
